ALTER TABLE public.ordenes_trabajo ADD COLUMN IF NOT EXISTS cantidad_ejecutada numeric NOT NULL DEFAULT 0;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS gerencia_id bigint REFERENCES public.gerencias(id) ON DELETE SET NULL;

CREATE TABLE public.ot_bitacora (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ot_id bigint NOT NULL REFERENCES public.ordenes_trabajo(id) ON DELETE CASCADE,
  tipo text NOT NULL DEFAULT 'avance' CHECK (tipo IN ('avance','inicio','parada','terminado','reanudacion')),
  piezas numeric NOT NULL DEFAULT 0 CHECK (piezas >= 0),
  hh numeric NOT NULL DEFAULT 0 CHECK (hh >= 0),
  nota text,
  usuario_id uuid DEFAULT auth.uid(),
  fecha timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON public.ot_bitacora(ot_id);
GRANT SELECT, INSERT ON public.ot_bitacora TO authenticated;
GRANT ALL ON public.ot_bitacora TO service_role;
ALTER TABLE public.ot_bitacora ENABLE ROW LEVEL SECURITY;
CREATE POLICY "leer" ON public.ot_bitacora FOR SELECT TO authenticated USING (true);
CREATE POLICY "registrar" ON public.ot_bitacora FOR INSERT TO authenticated
  WITH CHECK ((public.is_editor(auth.uid()) OR public.has_role(auth.uid(),'operario')) AND usuario_id = auth.uid());

CREATE OR REPLACE FUNCTION public.bitacora_acumular() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF NEW.piezas > 0 OR NEW.hh > 0 THEN
    UPDATE ordenes_trabajo SET
      cantidad_ejecutada = cantidad_ejecutada + NEW.piezas,
      hh_ejecutadas = hh_ejecutadas + NEW.hh,
      avance = CASE WHEN COALESCE(cantidad,0) > 0 AND NEW.piezas > 0
                    THEN LEAST(100, ROUND((cantidad_ejecutada + NEW.piezas) / cantidad * 100, 1)) ELSE avance END
    WHERE id = NEW.ot_id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_bitacora_acumular AFTER INSERT ON public.ot_bitacora FOR EACH ROW EXECUTE FUNCTION public.bitacora_acumular();