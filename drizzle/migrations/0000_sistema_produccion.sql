CREATE TABLE public.estados_op (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre text NOT NULL, orden int NOT NULL DEFAULT 0, activo boolean NOT NULL DEFAULT true);
CREATE TABLE public.estados_ot (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre text NOT NULL, orden int NOT NULL DEFAULT 0, activo boolean NOT NULL DEFAULT true);
CREATE TABLE public.ordenes_produccion (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero text NOT NULL UNIQUE, fecha date NOT NULL DEFAULT current_date,
