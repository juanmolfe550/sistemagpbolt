  tipo_produccion_id bigint REFERENCES public.tipos_produccion(id),
  producto text NOT NULL, descripcion text, especificaciones text,
  cantidad numeric NOT NULL DEFAULT 1, unidad_medida text,
  tiempo_entrega text, fecha_compromiso date, costo_fabricacion numeric(15,2) DEFAULT 0,
  documentacion_referencia text, prioridad text,
  estado_id bigint REFERENCES public.estados_op(id),
  gerencia_id bigint REFERENCES public.gerencias(id),
  responsable_id bigint REFERENCES public.empleados(id),
  revision text, fecha_ultimo_cambio date, motivo_cambio text,
  fecha_asignacion date, fecha_inicio_plan date, fecha_fin_plan date,
  avance numeric NOT NULL DEFAULT 0, hh_planificadas numeric NOT NULL DEFAULT 0, hh_ejecutadas numeric NOT NULL DEFAULT 0,
  requisitos text, no_conformidad boolean NOT NULL DEFAULT false, identificacion_no_conformidad text, tratamiento text,
  fecha_inicio_real date, fecha_fin_real date, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.ordenes_trabajo (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero text NOT NULL UNIQUE,
  op_id bigint NOT NULL REFERENCES public.ordenes_produccion(id) ON DELETE CASCADE,
  revision text, objeto text, descripcion text, especificaciones text,
  cantidad numeric DEFAULT 1, unidad_medida text, documentacion_referencia text,
  gerencia_id bigint REFERENCES public.gerencias(id),
  responsable_id bigint REFERENCES public.empleados(id),
  fecha_elaboracion date, fecha_asignacion date, fecha_inicio_plan date, fecha_fin_plan date,
  hh_planificadas numeric NOT NULL DEFAULT 0, prioridad text, tiene_dependencia boolean NOT NULL DEFAULT false,
  estado_id bigint REFERENCES public.estados_ot(id),
  hh_ejecutadas numeric NOT NULL DEFAULT 0, avance numeric NOT NULL DEFAULT 0,
  fecha_inicio_real date, fecha_fin_real date, resultado_ejecucion text,
  no_programada boolean NOT NULL DEFAULT false, no_conformidad boolean NOT NULL DEFAULT false,
  tipo_restriccion text, tratamiento_no_conformidad text, accion_requerida text,
  responsable_accion_id bigint REFERENCES public.empleados(id),
  fecha_compromiso_accion date, requisitos text, observaciones text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON public.ordenes_trabajo(op_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.gerencias, public.clientes, public.empleados, public.tipos_produccion, public.estados_op, public.estados_ot, public.ordenes_produccion, public.ordenes_trabajo TO authenticated;
GRANT ALL ON public.gerencias, public.clientes, public.empleados, public.tipos_produccion, public.estados_op, public.estados_ot, public.ordenes_produccion, public.ordenes_trabajo TO service_role;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['gerencias','clientes','empleados','tipos_produccion','estados_op','estados_ot','ordenes_produccion','ordenes_trabajo'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('CREATE POLICY "leer" ON public.%I FOR SELECT TO authenticated USING (true)', t);
    EXECUTE format('CREATE POLICY "crear" ON public.%I FOR INSERT TO authenticated WITH CHECK (public.is_editor(auth.uid()))', t);
    EXECUTE format('CREATE POLICY "borrar" ON public.%I FOR DELETE TO authenticated USING (public.is_editor(auth.uid()))', t);
    IF t = 'ordenes_trabajo' THEN
      EXECUTE format('CREATE POLICY "editar" ON public.%I FOR UPDATE TO authenticated USING (public.is_editor(auth.uid()) OR public.has_role(auth.uid(),''operario''))', t);
    ELSE
      EXECUTE format('CREATE POLICY "editar" ON public.%I FOR UPDATE TO authenticated USING (public.is_editor(auth.uid()))', t);
    END IF;
  END LOOP;
END $$;

