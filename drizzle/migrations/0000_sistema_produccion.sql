CREATE TABLE public.clientes (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre text NOT NULL, rif text, direccion text, telefono text, correo text, activo boolean NOT NULL DEFAULT true);
CREATE TABLE public.empleados (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre_completo text NOT NULL, cedula text, cargo text, gerencia_id bigint REFERENCES public.gerencias(id) ON DELETE SET NULL, correo text, telefono text, activo boolean NOT NULL DEFAULT true);
